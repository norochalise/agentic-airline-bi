import json
from pathlib import Path
from typing import Any

from agentic_bi.core.agent import run_agent
from agentic_bi.evaluation.failure_analysis import (
    FailureRecord,
    classify_failures,
    summarize_failure_categories,
)


PROJECT_ROOT = Path(__file__).resolve().parents[3]

CASES_PATH = (
    PROJECT_ROOT
    / "evals"
    / "agent_end_to_end_cases.json"
)


def load_cases() -> list[dict[str, Any]]:
    """Load the frozen M15 end-to-end evaluation cases."""

    with CASES_PATH.open(
        "r",
        encoding="utf-8",
    ) as file:
        data = json.load(file)

    return data["cases"]


def get_used_tools(
    observations: list[dict[str, Any]],
) -> list[str]:
    """Return successfully executed tool names."""

    return [
        observation["tool"]
        for observation in observations
        if "tool" in observation
    ]


def find_tool_observation(
    observations: list[dict[str, Any]],
    expected_tool: str,
) -> dict[str, Any] | None:
    """Find the first successful observation for a tool."""

    for observation in observations:
        if observation.get("tool") == expected_tool:
            return observation

    return None


def arguments_match(
    actual_arguments: dict[str, Any],
    expected_arguments: dict[str, Any] | None,
) -> bool:
    """
    Check deterministic arguments.

    Knowledge-search query wording is generated by the model,
    so cases with expected_arguments=None do not require exact
    argument matching.
    """

    if expected_arguments is None:
        return True

    for key, expected_value in expected_arguments.items():
        if actual_arguments.get(key) != expected_value:
            return False

    return True


def answer_contains_required_facts(
    answer: str,
    required_facts: list[str],
) -> bool:
    """Check simple required factual markers in final answer."""

    normalized_answer = answer.lower()

    return all(
        str(fact).lower() in normalized_answer
        for fact in required_facts
    )


def yes_no(value: bool) -> str:
    """Convert a boolean evaluation result into readable output."""

    return "PASS" if value else "FAIL"


def print_failure_record(
    failure: FailureRecord,
) -> None:
    """Print one classified failure."""

    print(f"    Category: {failure.category}")
    print(f"    Message: {failure.message}")

    if failure.details:
        print(f"    Details: {failure.details}")


def main() -> None:
    cases = load_cases()

    total = len(cases)

    skill_passes = 0
    tool_passes = 0
    argument_passes = 0
    stop_passes = 0
    error_passes = 0
    answer_passes = 0
    full_passes = 0

    # M15-style failed case records.
    failed_cases: list[dict[str, Any]] = []

    # M16 classified failure records.
    all_classified_failures: list[FailureRecord] = []

    print("=" * 72)
    print("M15 + M16 AGENT EVALUATION")
    print("=" * 72)
    print(f"Cases: {total}")
    print()

    for index, case in enumerate(cases, start=1):

        case_id = case["id"]
        question = case["question"]

        expected_skill = case["expected_skill"]
        expected_tool = case["expected_tool"]
        expected_arguments = case["expected_arguments"]
        expected_stop_reason = case[
            "expected_stop_reason"
        ]

        required_facts = case.get(
            "answer_must_contain",
            [],
        )

        print("-" * 72)
        print(f"[{index}/{total}] {case_id}")
        print(f"Question: {question}")

        # ====================================================
        # RUN THE REAL AGENT
        # ====================================================

        try:
            result = run_agent(
                question=question,
                verbose=False,
            )

        except Exception as exc:
            print("AGENT EXECUTION: FAIL")
            print(
                f"Exception: {type(exc).__name__}: {exc}"
            )

            # An exception prevented normal evaluation.
            failure = FailureRecord(
                category="agent_execution_exception",
                message=(
                    "The agent raised an exception before "
                    "the evaluation checks could complete."
                ),
                details={
                    "exception_type": type(exc).__name__,
                    "error": str(exc),
                },
            )

            all_classified_failures.append(failure)

            failed_cases.append(
                {
                    "id": case_id,
                    "failure_records": [failure],
                }
            )

            print_failure_record(failure)
            print()

            continue

        # ====================================================
        # SKILL
        # ====================================================

        skill_ok = (
            result.selected_skill
            == expected_skill
        )

        skill_passes += int(skill_ok)

        # ====================================================
        # TOOL
        # ====================================================

        used_tools = get_used_tools(
            result.observations
        )

        tool_ok = (
            expected_tool in used_tools
        )

        tool_passes += int(tool_ok)

        # ====================================================
        # ARGUMENTS
        # ====================================================

        expected_observation = (
            find_tool_observation(
                result.observations,
                expected_tool,
            )
        )

        if expected_observation is None:
            argument_ok = False
            actual_arguments = None

        else:
            actual_arguments = (
                expected_observation.get(
                    "arguments",
                    {},
                )
            )

            argument_ok = arguments_match(
                actual_arguments=actual_arguments,
                expected_arguments=expected_arguments,
            )

        argument_passes += int(
            argument_ok
        )

        # ====================================================
        # STOP REASON
        # ====================================================

        stop_ok = (
            result.stop_reason
            == expected_stop_reason
        )

        stop_passes += int(stop_ok)

        # ====================================================
        # ERRORS
        # ====================================================

        errors_ok = (
            len(result.errors) == 0
        )

        error_passes += int(errors_ok)

        # ====================================================
        # FINAL ANSWER
        # ====================================================

        answer_ok = (
            bool(result.final_answer.strip())
            and answer_contains_required_facts(
                answer=result.final_answer,
                required_facts=required_facts,
            )
        )

        answer_passes += int(
            answer_ok
        )

        # ====================================================
        # FULL CASE
        # ====================================================

        full_ok = all(
            [
                skill_ok,
                tool_ok,
                argument_ok,
                stop_ok,
                errors_ok,
                answer_ok,
            ]
        )

        full_passes += int(
            full_ok
        )

        # ====================================================
        # M16 FAILURE CLASSIFICATION
        # ====================================================

        case_failures = classify_failures(
            skill_ok=skill_ok,
            tool_ok=tool_ok,
            argument_ok=argument_ok,
            stop_ok=stop_ok,
            errors_ok=errors_ok,
            answer_ok=answer_ok,
            expected_skill=expected_skill,
            actual_skill=result.selected_skill,
            expected_tool=expected_tool,
            used_tools=used_tools,
            expected_arguments=expected_arguments,
            actual_arguments=actual_arguments,
            expected_stop_reason=expected_stop_reason,
            actual_stop_reason=result.stop_reason,
            errors=result.errors,
        )

        all_classified_failures.extend(
            case_failures
        )

        # ====================================================
        # PRINT CASE DETAILS
        # ====================================================

        print(
            "Skill:",
            yes_no(skill_ok),
            f"(expected={expected_skill}, "
            f"actual={result.selected_skill})",
        )

        print(
            "Tool:",
            yes_no(tool_ok),
            f"(expected={expected_tool}, "
            f"used={used_tools})",
        )

        print(
            "Arguments:",
            yes_no(argument_ok),
        )

        if expected_arguments is not None:
            print(
                "  Expected:",
                expected_arguments,
            )

            print(
                "  Actual:",
                actual_arguments,
            )

        print(
            "Stop reason:",
            yes_no(stop_ok),
            f"(expected={expected_stop_reason}, "
            f"actual={result.stop_reason})",
        )

        print(
            "No runtime errors:",
            yes_no(errors_ok),
            f"(errors={len(result.errors)})",
        )

        print(
            "Answer requirements:",
            yes_no(answer_ok),
            f"(required={required_facts})",
        )

        print(
            "FULL CASE:",
            yes_no(full_ok),
        )

        # ====================================================
        # PRINT / RECORD FAILURE DETAILS
        # ====================================================

        if case_failures:

            print("Failure analysis:")

            for failure in case_failures:
                print_failure_record(failure)

            failed_cases.append(
                {
                    "id": case_id,
                    "failure_records":
                        case_failures,
                    "final_answer":
                        result.final_answer,
                }
            )

        print()

    # ========================================================
    # M15 SUMMARY
    # ========================================================

    print("=" * 72)
    print("M15 EVALUATION SUMMARY")
    print("=" * 72)

    print(
        f"Skill accuracy: "
        f"{skill_passes}/{total} "
        f"= {skill_passes / total:.1%}"
    )

    print(
        f"Tool success: "
        f"{tool_passes}/{total} "
        f"= {tool_passes / total:.1%}"
    )

    print(
        f"Argument success: "
        f"{argument_passes}/{total} "
        f"= {argument_passes / total:.1%}"
    )

    print(
        f"Stop-reason success: "
        f"{stop_passes}/{total} "
        f"= {stop_passes / total:.1%}"
    )

    print(
        f"Error-free runs: "
        f"{error_passes}/{total} "
        f"= {error_passes / total:.1%}"
    )

    print(
        f"Answer requirement success: "
        f"{answer_passes}/{total} "
        f"= {answer_passes / total:.1%}"
    )

    print()

    print(
        f"FULL END-TO-END PASS RATE: "
        f"{full_passes}/{total} "
        f"= {full_passes / total:.1%}"
    )

    # ========================================================
    # M16 FAILURE ANALYSIS SUMMARY
    # ========================================================

    print()
    print("=" * 72)
    print("M16 FAILURE ANALYSIS SUMMARY")
    print("=" * 72)

    if all_classified_failures:

        category_summary = (
            summarize_failure_categories(
                all_classified_failures
            )
        )

        print(
            f"Failed agent cases: "
            f"{len(failed_cases)}"
        )

        print(
            f"Failure records: "
            f"{len(all_classified_failures)}"
        )

        print()

        print("Failure categories:")

        for category, count in sorted(
            category_summary.items()
        ):
            print(
                f"  {category}: {count}"
            )

        print()
        print("Cases to investigate:")

        for failed_case in failed_cases:

            print()
            print(f"  {failed_case['id']}")

            for failure in (
                failed_case[
                    "failure_records"
                ]
            ):
                print(
                    f"    - {failure.category}: "
                    f"{failure.message}"
                )

    else:

        print(
            "No failures detected in the "
            "current evaluation set."
        )

        print(
            "Failure classifier produced "
            "0 failure records."
        )

    print()

    print(
        "NOTE: These results apply only to the "
        "current frozen M15 evaluation set."
    )


if __name__ == "__main__":
    main()